const dictionaries: Record<Language, Record<string, string>> = { en, es };
const STORAGE_KEY = "yggdrasil.console.language";

/** Restores the language this browser chose last, else the browser's own. */
export function initLanguage(): void {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch {
    // storage blocked
  }
  setLanguage(resolveLanguage(saved, navigator.language));
}

export function chooseLanguage(language: Language): void {
  setLanguage(language);
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // not remembered
  }
}

/** Re-renders on language change; returns the console's `t`. Accepts any string key (dynamic keys fall back to the key). */
export function useT(): (key: ConsoleKey | string, vars?: Record<string, string | number>) => string {
  const language = useSyncExternalStore(subscribeLanguage, getLanguage);
  return (key, vars) => translate(dictionaries[language], en, key, vars);
}
