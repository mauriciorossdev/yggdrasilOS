// Builds src/components.css: the rules from app-desktop's styles.css that style the kit's
// chat, settings and agents components, for apps that don't load that stylesheet (the web
// console). app-desktop keeps loading its own styles.css; this is a copy, kept in sync by
// running this script (a test fails when it's stale).
//
//   pnpm --filter @yggdrasil/ui-kit sync-css
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const kitRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
export const DESKTOP_CSS = join(kitRoot, "../app-desktop/src/renderer/src/styles.css");
export const OUTPUT = join(kitRoot, "src/components.css");
const COMPONENT_DIRS = ["chat", "settings", "agents"];

/** Class names the kit's components can render (static class strings and template-literal parts). */
export function componentClasses() {
  const classes = new Set();
  for (const dir of COMPONENT_DIRS) {
    for (const file of readdirSync(join(kitRoot, "src", dir))) {
      if (!file.endsWith(".tsx")) continue;
      const source = readFileSync(join(kitRoot, "src", dir, file), "utf8");
      for (const m of source.matchAll(/className=\{?[`"]([^`"]+)[`"]/g)) {
        for (const token of m[1].replace(/\$\{[^}]*\}/g, " ").split(/\s+/)) {
          if (/^[a-z][a-z0-9_-]*[a-z0-9]$/.test(token)) classes.add(token);
        }
      }
    }
  }
  return classes;
}

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

/** Splits CSS into top-level blocks: { prelude, body } (body without the outer braces). */
function blocks(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) break;
    let depth = 1;
    let j = open + 1;
    while (j < css.length && depth > 0) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") depth--;
      j++;
    }
    out.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j - 1) });
    i = j;
  }
  return out;
}

function mentionsAny(selector, classes) {
  for (const m of selector.matchAll(/\.([a-zA-Z0-9_-]+)/g)) if (classes.has(m[1])) return true;
  return false;
}

function rule(prelude, body) {
  const decls = body
    .split(";")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => `  ${d.replace(/\s+/g, " ")};`)
    .join("\n");
  return `${prelude.replace(/\s+/g, " ")} {\n${decls}\n}`;
}

/** The generated stylesheet for the given desktop CSS and class set. */
export function buildComponentsCss(desktopCss, classes) {
  const all = blocks(stripComments(desktopCss));
  const picked = [];
  const animations = new Set();
  const note = (body) => {
    for (const m of body.matchAll(/animation(?:-name)?\s*:\s*([^;]+)/g)) {
      for (const word of m[1].split(/[\s,]+/)) animations.add(word);
    }
  };
  for (const b of all) {
    if (b.prelude.startsWith("@media") || b.prelude.startsWith("@supports")) {
      const inner = blocks(b.body).filter((r) => mentionsAny(r.prelude, classes));
      if (inner.length === 0) continue;
      inner.forEach((r) => note(r.body));
      picked.push(`${b.prelude.replace(/\s+/g, " ")} {\n${inner.map((r) => rule(r.prelude, r.body).replace(/^/gm, "  ")).join("\n\n")}\n}`);
    } else if (!b.prelude.startsWith("@") && mentionsAny(b.prelude, classes)) {
      note(b.body);
      picked.push(rule(b.prelude, b.body));
    }
  }
  const keyframes = all
    .filter((b) => b.prelude.startsWith("@keyframes") && animations.has(b.prelude.split(/\s+/)[1]))
    .map((b) => `${b.prelude} {\n${blocks(b.body).map((r) => rule(r.prelude, r.body).replace(/^/gm, "  ")).join("\n")}\n}`);
  return [
    "/* GENERATED by `pnpm --filter @yggdrasil/ui-kit sync-css` from app-desktop's styles.css — do not edit.",
    "   Styles for the kit's chat, settings and agents components, for apps without that stylesheet. */",
    "",
    [...picked, ...keyframes].join("\n\n"),
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = buildComponentsCss(readFileSync(DESKTOP_CSS, "utf8"), componentClasses());
  writeFileSync(OUTPUT, css);
  console.log(`wrote ${OUTPUT} (${css.length} bytes)`);
}
